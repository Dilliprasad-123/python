
# ============ conditional statements ==============

# 1. If statement
x = 10
if x > 5:
    print("x is greater than 5")

# 2. If-else statement
y = 3
if y % 2 == 0:
    print("y is even")
else:
    print("y is odd")

# 3. If-elif-else statement
z = 7
if z < 0:
    print("z is negative")
elif z == 0:
    print("z is zero")
else:
    print("z is positive")